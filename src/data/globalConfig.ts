function createRegionFormatter(locale: string): Intl.DisplayNames | null {
  try {
    if (typeof Intl !== 'undefined' && typeof Intl.DisplayNames === 'function') {
      return new Intl.DisplayNames([locale], { type: 'region' });
    }
  } catch {
    // Fallback if runtime does not support Intl.DisplayNames
  }
  return null;
}

const REGION_DISPLAY_AR = createRegionFormatter('ar');
const REGION_DISPLAY_EN = createRegionFormatter('en');
const REGION_DISPLAY_FR = createRegionFormatter('fr');
const REGION_DISPLAY_ES = createRegionFormatter('es');

function resolveRegionName(formatter: Intl.DisplayNames | null, code: string): string {
  try {
    return formatter?.of(code) || code;
  } catch {
    return code;
  }
}

function defaultWalletsForRegion(region: WorldRegion): string[] {
  switch (region) {
    case 'Europe':
      return ['Wise', 'Revolut', 'PayPal', 'Payoneer', 'Western Union Digital'];
    case 'Africa':
      return ['M-Pesa', 'Airtel Money', 'Orange Money', 'Chipper Cash', 'Western Union Digital', 'Wise'];
    case 'Asia':
      return ['PayPal', 'Wise', 'Payoneer', 'Alipay / GrabPay', 'Western Union Digital'];
    case 'Americas':
      return ['PayPal', 'Wise', 'Payoneer', 'Mercado Pago', 'Western Union Digital'];
    case 'Oceania':
      return ['PayPal', 'Wise', 'Payoneer', 'Apple Pay', 'Western Union Digital'];
    default:
      return ['PayPal', 'Wise', 'Western Union Digital', 'Payoneer'];
  }
}

function buildGlobalCountries(): CountryConfig[] {
  const seen = new Set<string>(FEATURED_COUNTRIES.map((c) => c.code));
  const extra: CountryConfig[] = [];

  for (const [code, region, dialCode, currency] of WORLD_COUNTRIES_COMPACT) {
    if (seen.has(code)) continue;
    seen.add(code);
    extra.push({
      code,
      nameAr: resolveRegionName(REGION_DISPLAY_AR, code),
      nameEn: resolveRegionName(REGION_DISPLAY_EN, code),
      nameFr: resolveRegionName(REGION_DISPLAY_FR, code),
      nameEs: resolveRegionName(REGION_DISPLAY_ES, code),
      region,
      dialCode,
      currency,
      usdRate: CURRENCY_USD_RATES[currency] ?? 1,
      walletProviders: defaultWalletsForRegion(region),
      ibanHint: `${code}-IBAN / ACCOUNT NUMBER + SWIFT`,
      featured: false,
    });
  }

  return [...FEATURED_COUNTRIES, ...extra];
}

export const GLOBAL_COUNTRIES: CountryConfig[] = buildGlobalCountries();


export function getCountryDisplayName(country: CountryConfig, lang: 'ar' | 'en' | 'fr' | 'es'): string {
  switch (lang) {
    case 'ar':
      return country.nameAr;
    case 'fr':
      return country.nameFr;
    case 'es':
      return country.nameEs;
    default:
      return country.nameEn;
  }
}

export function convertToUsd(amount: number, currency: string): number {
  const rate = CURRENCY_USD_RATES[currency] ?? 1;
  return Math.round(amount * rate * 100) / 100;
}

export function formatCurrency(amount: number, currency: string): string {
  return `${new Intl.NumberFormat('en-US', { maximumFractionDigits: 2 }).format(amount)} ${currency}`;
}
